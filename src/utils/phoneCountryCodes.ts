export function findPhoneCountryCode(iso: string): PhoneCountryCodeOption {
  return PHONE_COUNTRY_CODES.find((option) => option.iso === iso) ?? PHONE_COUNTRY_CODES[0]
}

export function sanitizePhoneDigits(value: string, maxDigits: number): string {
  return value.replace(/\D/g, '').slice(0, maxDigits)
}

export function parseInternationalPhone(phone: string | null | undefined): {
  iso: string
  localNumber: string
} {
  const compact = (phone ?? '').replace(/[\s\-()]/g, '')
  const matched = [...PHONE_COUNTRY_CODES]
    .sort((a, b) => b.dialCode.length - a.dialCode.length)
    .find((option) => compact.startsWith(option.dialCode))

  if (!matched) {
    const fallback = findPhoneCountryCode(DEFAULT_PHONE_COUNTRY_ISO)
    return {
      iso: fallback.iso,
      localNumber: sanitizePhoneDigits(compact, fallback.maxDigits),
    }
  }

  return {
    iso: matched.iso,
    localNumber: sanitizePhoneDigits(compact.slice(matched.dialCode.length), matched.maxDigits),
  }
}
