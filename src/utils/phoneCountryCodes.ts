export type PhoneCountryCodeOption = {
  iso: string
  country: string
  dialCode: string
  minDigits: number
  maxDigits: number
}

const defaultDigits = (dialCode: string) => Math.max(4, 15 - dialCode.replace(/\D/g, '').length)

function code(iso: string, country: string, dialCode: string, digits?: number): PhoneCountryCodeOption {
  const maxDigits = digits ?? defaultDigits(dialCode)
  return { iso, country, dialCode, minDigits: digits ?? 4, maxDigits }
}

